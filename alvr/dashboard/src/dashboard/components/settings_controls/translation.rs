//! Traditional-Chinese display translations applied at the render layer.
//!
//! Settings labels/options are matched against the untranslated `id` (struct
//! field name, enum-variant name, or preset-option display name) when the UI
//! reads/writes the session and when presets are matched, so we translate ONLY
//! the *displayed* string here and never the `id`. Help/notice text is keyed by
//! its exact English source literal (the settings-schema derive stores only
//! explicit `strings(...)` literals, never doc comments, so the match is exact).
//! Missing keys fall back to the original English. `settings.rs` is untouched.
//!
//! Generated: starter table (tabs + builtin presets) merged with an automated
//! sweep of `settings.rs`. Edit freely — this is plain data.

use std::collections::{HashMap, HashSet};
use std::sync::OnceLock;

/// Translate a settings label by its stable English `id`.
pub fn tr_label(id: &str) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| LABELS.iter().copied().collect())
        .get(id)
        .copied()
}

/// Translate a help/notice string by its exact English source text.
pub fn tr_text(english: &str) -> Option<&'static str> {
    static MAP: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    MAP.get_or_init(|| TEXTS.iter().copied().collect())
        .get(english)
        .copied()
}

/// Advanced / rarely-touched settings curated out of the UI. Hidden at the
/// render layer only — the values still live in the session with their defaults,
/// and removing a name here brings the setting straight back.
pub fn is_hidden(id: &str) -> bool {
    static SET: OnceLock<HashSet<&'static str>> = OnceLock::new();
    SET.get_or_init(|| HIDDEN.iter().copied().collect())
        .contains(id)
}

/// Whole settings tabs curated out — only the streaming pipeline (presets /
/// video / audio / connection) stays. Drop a name here to restore the tab.
pub fn is_hidden_tab(id: &str) -> bool {
    matches!(id, "headset" | "extra")
}

